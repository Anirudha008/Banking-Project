CREATE TABLE loans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id BIGINT NOT NULL, account_id BIGINT NOT NULL,
 principal NUMERIC(19,2) NOT NULL, annual_interest_rate NUMERIC(8,4) NOT NULL, term_months INTEGER NOT NULL,
 outstanding NUMERIC(19,2) NOT NULL, status VARCHAR(20) NOT NULL, created_at TIMESTAMP NOT NULL
);
CREATE TABLE repayments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, loan_id BIGINT NOT NULL REFERENCES loans(id),
 amount NUMERIC(19,2) NOT NULL CHECK(amount > 0), paid_at TIMESTAMP NOT NULL
);
