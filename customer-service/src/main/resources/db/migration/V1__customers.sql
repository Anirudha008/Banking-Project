CREATE TABLE customers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 first_name VARCHAR(60) NOT NULL, last_name VARCHAR(60) NOT NULL, date_of_birth DATE NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE, phone_number VARCHAR(20) NOT NULL UNIQUE,
 address VARCHAR(300) NOT NULL, kyc_status VARCHAR(20) NOT NULL,
 status VARCHAR(20) NOT NULL, created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL
);
