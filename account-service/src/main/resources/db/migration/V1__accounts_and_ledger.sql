CREATE TABLE accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id BIGINT NOT NULL,
 account_number VARCHAR(24) NOT NULL UNIQUE, account_type VARCHAR(20) NOT NULL,
 balance NUMERIC(19,2) NOT NULL CHECK(balance >= 0), status VARCHAR(20) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMP NOT NULL
);
CREATE TABLE account_transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id BIGINT NOT NULL REFERENCES accounts(id),
 transaction_type VARCHAR(30) NOT NULL, amount NUMERIC(19,2) NOT NULL CHECK(amount > 0),
 previous_balance NUMERIC(19,2) NOT NULL, new_balance NUMERIC(19,2) NOT NULL,
 reference VARCHAR(80) NOT NULL, created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_tx_account_created ON account_transactions(account_id,created_at DESC);
CREATE TABLE transfer_idempotency (
 idempotency_key VARCHAR(100) PRIMARY KEY, request_hash VARCHAR(64) NOT NULL,
 response_json VARCHAR(4000) NOT NULL, created_at TIMESTAMP NOT NULL
);
